/// 系统通告分类（2026-10-31 后续治理）：决定一条通告的**去向与留存**。
///
/// 背景：原「本轮记录」账本把会话内全部 [TrackNote] 无差别累积，多轮会话里
/// 同一条事实（引擎就绪 / 插件挂载 / CoW 重名）反复记账 → 面板刷屏。治理按
/// 语义三分，各归其位：
/// - [fact]：本会话**持久成立**的配置 / 状态事实（引擎就绪、插件自动挂载、
///   工具已激活、CoW 重名跳过、服务卸载、未信任插件跳过、配额/快照损坏等）。
///   进入「本轮记录」账本**单槽**，仅留最新一份（同文案重复轮次覆盖式收敛）。
/// - [error]：执行中**出错、须当场可见**（记忆写入失败、连接中断、挂载失败、
///   权限/slot 事件、CoW 同步降级）。回**对话流内联**，发生当场即见，不进账本
///   （避免被后到的良性事实覆盖而吞掉错误）。
/// - [process]：**纯瞬态**进度 / 遥测，无持久意义（工具进度回显、plan echo、
///   资源变更、端侧加载中、任务完成）。**不收纳**，仅由页面层瞬态 pill 一闪即过。
enum TrackNoticeCategory {
  fact,
  error,
  process,
}
